"""Automatic group labels for channels NOT in config/channel_groups.csv, by objective markers only.
C  if profile has Russian-infrastructure markers (Roskomnadzor registry, gosuslugi, MAX, VK, Dzen, Rutube, OK)
   or >=30% of its outbound links in the window go to Russian domains (.ru/.su/.рф, vk.com, max.ru, dzen.ru, rutube.ru).
U  otherwise (needs manual review). Output: config/channel_groups_auto.csv (regenerated, never hand-edited).
"""
import csv, json, re, sys
from collections import Counter
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
PROFILE = re.compile(r"knd\.gov\.ru|gosuslugi|max\.ru|vk\.com|dzen\.ru|rutube|ok\.ru|роскомнадзор|РКН", re.I)
RU_DOM = re.compile(r"https?://(?:[^/]+\.)?(?:[^/]+\.ru|[^/]+\.su|[^/]+\.xn--p1ai|vk\.com|max\.ru|dzen\.ru|rutube\.ru|ok\.ru)(?:/|$)", re.I)
names = sys.argv[1].split("+")
manual = {r["channel"].lower() for r in csv.DictReader(l for l in open(ROOT / "config/channel_groups.csv") if not l.startswith("#"))}
chans, links = {}, Counter()
rulinks = Counter()
for n in names:
    d = ROOT / "data/raw/telegram_web" / n
    for l in (d / "channels.jsonl").open():
        c = json.loads(l); chans.setdefault(c["channel"], c)
    for l in (d / "posts.jsonl").open():
        p = json.loads(l)
        for u in p.get("links", []):
            if "t.me/" in u: continue
            links[p["channel"]] += 1
            rulinks[p["channel"]] += bool(RU_DOM.match(u))
rows = []
for ch, c in chans.items():
    if ch in manual: continue
    prof = bool(PROFILE.search((c.get("description") or "") + " " + (c.get("title") or "")))
    share = rulinks[ch] / links[ch] if links[ch] else 0
    grp = "C" if prof or (links[ch] >= 5 and share >= 0.3) else "U"
    rows.append({"channel": ch, "group": grp, "cb": "", "basis": f"auto: profile_marker={prof}, ru_link_share={share:.2f} (n={links[ch]})"})
with open(ROOT / "config/channel_groups_auto.csv", "w", newline="") as f:
    f.write("# AUTO-GENERATED by src/analysis/auto_groups.py; manual file has priority.\n")
    w = csv.DictWriter(f, fieldnames=["channel", "group", "cb", "basis"]); w.writeheader(); w.writerows(rows)
print(Counter(r["group"] for r in rows))
