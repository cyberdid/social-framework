COMPILED = {k: re.compile(v["re"], re.I) for k, v in CODEBOOK.items()}
SENT = re.compile(r"(?<=[.!?\n])\s+")


def tag(text: str) -> list[str]:
    text = text or ""
    out = []
    for k, rx in COMPILED.items():
        if k == "N2_death_torture":
            # negation-aware: a sentence like "загиблих і травмованих немає" does not carry N2
            if any(rx.search(s) and not NEGATION.search(s) for s in SENT.split(text)):
                out.append(k)
        elif rx.search(text):
            out.append(k)
    return out
